#!/usr/bin/env python3
# gen_cat.py - the market monitor's catalogue from PicoAmp's engine/pva_markets_cat.c:
#   mk_cat.inc   the regions and their lists (in the ROM)
#   MARKETS.CAT  the members of the indices (on the SD card, read when an index is opened)
#
# An instrument is  symbol, 0, name, 0, decimals  (one after the other).
#
# mk_cat.inc:
#   cat_regions:  the regions' names, 0-terminated
#   cat_codes:    their codes for MARKETS.INI (region=europe)
#   cat_lists:    per list: db region, dw name, dw items, db count; db FFh at the end
#
# MARKETS.CAT:
#   "MKCAT1", u16 directory size, u8 indices; per index: symbol 0, name 0,
#   u16 offset (from the file's start), u8 count; then the items of each.
#
# usage: gen_cat.py pva_markets_cat.c mk_cat.inc MARKETS.CAT
import re, sys

src = open(sys.argv[1], encoding='utf-8').read()

def items_of(body):
    return [(s, n, int(d)) for s, n, d in re.findall(r'\{\s*"((?:[^"\\]|\\.)*)",\s*"((?:[^"\\]|\\.)*)",\s*(\d+)\s*\}', body)]

arrays = {}
for name, body in re.findall(r'static const pva_mkt_item_t (\w+)\[\] = \{(.*?)\n\};', src, re.S):
    arrays[name] = items_of(body)

regions = re.search(r'pva_mkt_region_names\[\] = \{(.*?)NULL', src, re.S).group(1)
regions = re.findall(r'"([^"]*)"', regions)
codes = re.findall(r'"([^"]*)"', re.search(r'pva_mkt_region_codes\[\] = \{(.*?)NULL', src, re.S).group(1))
lists = re.findall(r'\{\s*(\d+),\s*"([^"]*)",\s*(\w+),\s*N\(\w+\)\s*\}',
                   re.search(r'pva_mkt_lists\[\] = \{(.*?)\n\};', src, re.S).group(1))
members = re.findall(r'\{\s*"([^"]*)",\s*"([^"]*)",\s*(\w+),\s*N\(\w+\)\s*\}',
                     re.search(r'pva_mkt_members\[\] = \{(.*?)\n\};', src, re.S).group(1))

def asm_str(s):
    out, cur = [], ''
    for ch in s:
        if ch == '"' or ord(ch) > 126:
            if cur: out.append('"%s"' % cur); cur = ''
            out.append(str(ord(ch) if ord(ch) < 256 else ord('?')))
        else:
            cur += ch
    if cur: out.append('"%s"' % cur)
    out.append('0')
    return ','.join(out)

def item_bytes(it):
    b = bytearray()
    for s, n, d in it:
        b += s.encode('latin-1', 'replace') + b'\0' + n.encode('latin-1', 'replace') + b'\0' + bytes([d])
    return b

o = ['; generated by gen_cat.py from PicoAmp\'s pva_markets_cat.c: do not edit', '']
o.append('cat_nregions equ %d' % len(regions))
o.append('cat_regions:')
for r in regions: o.append('        db ' + asm_str(r))
o.append('cat_codes:')
for c in codes: o.append('        db ' + asm_str(c))
o.append('cat_lists:')
for k, (reg, name, arr) in enumerate(lists):
    o.append('        db %s : dw cl_n%d, cl_i_%s : db %d' % (reg, k, arr, min(len(arrays[arr]), 100)))
o.append('        db #FF')
for k, (reg, name, arr) in enumerate(lists):
    o.append('cl_n%d: db %s' % (k, asm_str(name)))
done = set()
for reg, name, arr in lists:
    if arr in done: continue
    done.add(arr)
    o.append('cl_i_%s:' % arr)
    for s, n, d in arrays[arr][:100]:
        o.append('        db %s, %s, %d' % (asm_str(s), asm_str(n), d))
open(sys.argv[2], 'w').write('\n'.join(o) + '\n')

# MARKETS.CAT
dirb = bytearray()
for sym, name, arr in members:
    dirb += sym.encode() + b'\0' + name.encode('latin-1', 'replace') + b'\0' + b'\0\0' + b'\0'
head = 6 + 2 + 1
offs, data = [], bytearray()
base = head + len(dirb)
for sym, name, arr in members:
    offs.append(base + len(data))
    data += item_bytes(arrays[arr][:100])
dirb = bytearray()
for (sym, name, arr), off in zip(members, offs):
    dirb += sym.encode() + b'\0' + name.encode('latin-1', 'replace') + b'\0' + bytes([off & 255, off >> 8, min(len(arrays[arr]), 100)])
f = b'MKCAT1' + bytes([len(dirb) & 255, len(dirb) >> 8, len(members)]) + dirb + data
open(sys.argv[3], 'wb').write(f)
big = max(len(item_bytes(arrays[a][:100])) for _, _, a in members)
print('regions %d, lists %d (%d instruments), indices with members %d, MARKETS.CAT %d bytes, directory %d, largest member list %d bytes'
      % (len(regions), len(lists), sum(min(len(arrays[a]), 100) for _, _, a in lists), len(members), len(f), len(dirb), big))
